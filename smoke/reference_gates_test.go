var updateGates = flag.Bool("update-gates", false, "rewrite config/gate_measures_table.go from the reference model")

// gateMeasuresSource is config/gate_measures_table.go for the given measures.
func gateMeasuresSource(ms []config.GateMeasure) string {
	var b strings.Builder
	b.WriteString("// Code generated by go test ./smoke -run TestGateMeasures -update-gates. DO NOT EDIT.\n\n")
	b.WriteString("package config\n\n")
	b.WriteString("// gateMeasureTable is the measured gate's numbers, read off the reference\n")
	b.WriteString("// model (smoke/reference.go) by package smoke.\n")
	b.WriteString("var gateMeasureTable = []GateMeasure{\n")
	for _, m := range ms {
		mats := make([]string, len(m.Materials))
		for i, r := range m.Materials {
			mats[i] = fmt.Sprintf("%q", r)
		}
		fmt.Fprintf(&b, "\t{Age: %q, People: %s, Materials: []string{%s}, Income: %s, KeyTech: %q},\n",
			m.Age, config.GoLiteral(float64(m.People)), strings.Join(mats, ", "), config.GoLiteral(m.Income), m.KeyTech)
	}
	b.WriteString("}\n")
	return b.String()
}

// The measured gate's numbers are the reference model's: the table in config
// is what DeriveGateMeasures reads off the ordinary player's town at each
// gate. When the tables move, regenerate it with
//
//	go test ./smoke -run TestGateMeasures -update-gates
func TestGateMeasuresMatchTheModel(t *testing.T) {
	want := DeriveGateMeasures()
	if *updateGates {
		src, err := format.Source([]byte(gateMeasuresSource(want)))
		if err != nil {
			t.Fatal(err)
		}
		path := filepath.Join("..", "config", "gate_measures_table.go")
		if err := os.WriteFile(path, src, 0o644); err != nil {
			t.Fatal(err)
		}
		t.Logf("wrote %s: %d ages", path, len(want))
		return
	}
	got := config.GateMeasures()
	if len(got) != len(want) {
		t.Fatalf("config's table holds %d gates, the model has %d (go test ./smoke -run TestGateMeasures -update-gates)", len(got), len(want))
	}
	for i := range want {
		if !reflect.DeepEqual(got[i], want[i]) {
			t.Errorf("%s: the table says %+v, the model says %+v (go test ./smoke -run TestGateMeasures -update-gates)", want[i].Age, got[i], want[i])
		}
	}
}

// Every gate has a measure, in age order, with a main material and a
// population, and the town the model leaves each age with meets it.
func TestGateMeasuresCoverEveryGate(t *testing.T) {
	ages := config.Ages()
	got := config.GateMeasures()
	if len(got) != len(ages)-1 {
		t.Fatalf("%d measures for %d gates", len(got), len(ages)-1)
	}
	for i, m := range got {
		if m.Age != ages[i].Key {
			t.Errorf("measure %d is for %s, want %s", i, m.Age, ages[i].Key)
		}
		if m.People <= 0 || len(m.Materials) == 0 || m.Income <= 0 || m.KeyTech == "" {
			t.Errorf("%s: an empty measure %+v", m.Age, m)
		}
	}
}

// The ordinary player's walk under the measured gate meets every gate, and no
// later than under the building counts: the measures are what his town has at
// the end of the counts' stay, and the population (the reserve fills the homes
// as the food allows) can be there before the last building is. The readings
// are logged.
func TestGatePacingReading(t *testing.T) {
	v1, v2 := ReferenceGatePacing(false), ReferenceGatePacing(true)
	total1, total2 := 0.0, 0.0
	for i := range v1.Hours {
		total1 += v1.Hours[i]
		total2 += v2.Hours[i]
		t.Logf("%2d %-20s v1 %10.3f h  v2 %10.3f h", i+1, v1.Names[i], v1.Hours[i], v2.Hours[i])
		if v2.Hours[i] <= 0 || v2.Hours[i] > 1.01*v1.Hours[i] {
			t.Errorf("%s: %.3f h under the measured gate against %.3f h under the building counts", v1.Names[i], v2.Hours[i], v1.Hours[i])
		}
	}
	t.Logf("all ages: v1 %.2f d, v2 %.2f d", total1/24, total2/24)
}

// The model's population is the game's count: the workers, the reserve, the
// scholars and the soldiers, no more than the homes hold (but for the scholars
// and soldiers, who move in regardless), and every measure is that count at
// the end of the ordinary player's stay.
func TestGatePopulationCountsTheReserve(t *testing.T) {
	tb := newRefTables()
	walk := tb.walk("ordinary", 1, tb.refIncomes())
	sawReserve := 0
	for i, m := range config.GateMeasures() {
		end := walk.Runs[i].end
		heads := end.workers + end.scholars + end.soldiers
		if end.population < heads {
			t.Errorf("%s: population %.0f is below the %.0f people at work", m.Age, end.population, heads)
		}
		if limit := max(end.room, end.scholars+end.soldiers); end.population > limit {
			t.Errorf("%s: population %.0f is more than the homes hold (%.0f)", m.Age, end.population, limit)
		}
		if end.reserve > 0 {
			sawReserve++
		}
		if float64(m.People) > end.population || float64(m.People) < end.population-1 {
			t.Errorf("%s: the measure is %d, the town at the gate has %.1f", m.Age, m.People, end.population)
		}
	}
	if sawReserve < 10 {
		t.Errorf("the reserve is part of the population in only %d gates", sawReserve)
	}
}
